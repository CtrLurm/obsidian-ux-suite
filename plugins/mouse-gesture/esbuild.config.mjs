import esbuild from "esbuild";
import process from "node:process";

const production = process.argv[2] === "production";

const banner = `/*
Mouse Gesture for Obsidian (mouse-gesture) v1.0.0
Bundled from src/*.ts by esbuild. Do not edit this file directly.
*/`;

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: production ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: false,
});

if (production) {
  await context.rebuild();
  await context.dispose();
  console.log("已构建 main.js");
} else {
  await context.watch();
  console.log("监听 src/ 变化中……");
}
