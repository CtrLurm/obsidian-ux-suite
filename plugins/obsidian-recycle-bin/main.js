// src/main.ts
var RecycleBinPlugin = class extends import_obsidian4.Plugin {
  constructor() {
    super(...arguments);
    this.settings = { ...DEFAULT_SETTINGS };
    this.originalTrashFile = null;
    this.patchedTrashFile = null;
    this.saveTimer = null;
  }
  async onload() {
    await this.loadSettings();
    const adapter = this.app.vault.adapter;
    const basePath = typeof adapter.getBasePath === "function" ? adapter.getBasePath() : "";
    if (!basePath) {
      new import_obsidian4.Notice("\u56DE\u6536\u7AD9\u63D2\u4EF6\u4EC5\u652F\u6301\u684C\u9762\u7248\u672C\u5730 vault\u3002");
      return;
    }
    const pluginDir = `${this.app.vault.configDir}/plugins/${this.manifest.id}`;
    this.service = new RecycleBinService(this.app, basePath, pluginDir);
    await this.service.init();
    this.registerView(VIEW_TYPE_RECYCLE_BIN, (leaf) => new RecycleBinView(leaf, this));
    this.addRibbonIcon("trash-2", "\u6253\u5F00\u56DE\u6536\u7AD9", () => {
      void this.activateView();
    });
    this.addCommand({
      id: "open-recycle-bin",
      name: "\u6253\u5F00\u56DE\u6536\u7AD9",
      callback: () => {
        void this.activateView();
      }
    });
    this.addSettingTab(new RecycleBinSettingTab(this.app, this));
    this.installTrashInterceptor();
  }
  async loadSettings() {
    const data = await this.loadData();
    this.settings = {
      enabled: (data == null ? void 0 : data.enabled) !== false,
      notifyOnDelete: (data == null ? void 0 : data.notifyOnDelete) === true
    };
  }
  async saveSettings() {
    await this.saveData(this.settings);
  }
  saveSettingsDebounced() {
    if (this.saveTimer !== null) {
      window.clearTimeout(this.saveTimer);
    }
    this.saveTimer = window.setTimeout(() => {
      this.saveTimer = null;
      void this.saveSettings();
    }, 400);
  }
  installTrashInterceptor() {
    const fileManager = this.app.fileManager;
    if (typeof fileManager.trashFile !== "function") {
      new import_obsidian4.Notice("\u65E0\u6CD5\u63A5\u7BA1 Obsidian \u7684\u5220\u9664\u64CD\u4F5C\uFF1AtrashFile \u4E0D\u5B58\u5728\u3002");
      return;
    }
    this.originalTrashFile = fileManager.trashFile;
    const patched = (file) => this.handleTrash(file);
    this.patchedTrashFile = patched;
    fileManager.trashFile = patched;
    this.register(() => {
      if (this.patchedTrashFile && fileManager.trashFile === this.patchedTrashFile) {
        fileManager.trashFile = this.originalTrashFile;
      }
    });
  }
  async handleTrash(file) {
    if (!this.settings.enabled) {
      return this.originalTrashFile ? await this.originalTrashFile.call(this.app.fileManager, file) : false;
    }
    try {
      const item = await this.service.moveToBin(file);
      try {
        await this.app.vault.delete(file, true);
      } catch (error) {
        await this.service.removeItem(item.id);
        throw error;
      }
      if (this.settings.notifyOnDelete) {
        new import_obsidian4.Notice(`\u5DF2\u79FB\u5165\u56DE\u6536\u7AD9\uFF1A${item.originalPath}`, 3500);
      }
      this.refreshViews();
      return true;
    } catch (error) {
      new import_obsidian4.Notice(`\u5220\u9664\u5931\u8D25\uFF1A${errorMessage(error)}`, 6e3);
      return false;
    }
  }
  refreshViews() {
    for (const leaf of this.app.workspace.getLeavesOfType(VIEW_TYPE_RECYCLE_BIN)) {
      const view = leaf.view;
      if (view instanceof RecycleBinView) {
        void view.refresh();
      }
    }
  }
  async activateView() {
    var _a;
    const { workspace } = this.app;
    let leaf = (_a = workspace.getLeavesOfType(VIEW_TYPE_RECYCLE_BIN)[0]) != null ? _a : null;
    if (!leaf) {
      leaf = workspace.getRightLeaf(false);
      if (!leaf) {
        new import_obsidian4.Notice("\u65E0\u6CD5\u6253\u5F00\u56DE\u6536\u7AD9\u89C6\u56FE\u3002");
        return;
      }
      await leaf.setViewState({
        type: VIEW_TYPE_RECYCLE_BIN,
        active: true
      });
    }
    workspace.rightSplit.expand();
    await workspace.revealLeaf(leaf);
  }
  onunload() {
    if (this.saveTimer !== null) {
      window.clearTimeout(this.saveTimer);
      this.saveTimer = null;
    }
    const fileManager = this.app.fileManager;
    if (this.patchedTrashFile && fileManager.trashFile === this.patchedTrashFile) {
      fileManager.trashFile = this.originalTrashFile;
    }
  }
};
